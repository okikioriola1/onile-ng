function uploadedDocument(name: string, type: string, status: UploadedDocument['status'] = 'approved'): UploadedDocument {
  return {
    id: `${type}-${name.replace(/\s+/g, '-').toLowerCase()}`,
    name,
    type,
    status,
    required: true,
    uploadedAt: daysAgo(12),
  }
}

